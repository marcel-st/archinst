# Firewall: one nftables table (inet archinst) for IPv4 and IPv6.
# Only this table is ever replaced, so Docker's and sshguard's tables survive
# every change. A change is loaded on trial and rolled back automatically
# unless it is confirmed from a new SSH connection.

FW_FILE=/etc/archinst/firewall.nft          # confirmed ruleset, loaded at boot
FW_NEW=/etc/archinst/firewall.nft.new       # ruleset on trial
FW_SNIPPETS=/etc/archinst/nftables.d        # host-specific rules, *.nft
FW_MIGRATING=/run/archinst/firewall-migrating
FW_UNIT=archinst-firewall.service
FW_ROLLBACK=archinst-firewall-rollback      # transient timer + service

fw_pending() { systemctl is-active -q "$FW_ROLLBACK.timer"; }

fw_iptables_enabled() {
	systemctl is-enabled -q iptables.service 2>/dev/null ||
		systemctl is-enabled -q ip6tables.service 2>/dev/null
}

# nft set declaration; $1 = name, $2 = type, rest = elements
fw_set() {
	local name=$1 type=$2 IFS=,
	shift 2
	printf '  set %s {\n    type %s; flags interval; auto-merge;\n' "$name" "$type"
	(($#)) && printf '    elements = { %s }\n' "$*"
	printf '  }\n'
}

firewall_generate() {
	local src v4=() v6=() f
	for src in "${SSH_ALLOW[@]}" "${SSH_ALLOW_V4[@]}" "${SSH_ALLOW_V6[@]}"; do
		if [[ $src == *:* ]]; then v6+=("$src"); else v4+=("$src"); fi
	done

	cat <<-'EOF'
	# Generated by archinst (lib/firewall.sh); changes here are overwritten.
	# Host-specific rules: /etc/archinst/nftables.d/*.nft
	destroy table inet archinst
	table inet archinst {
	EOF
	fw_set ssh_v4 ipv4_addr "${v4[@]}"
	fw_set ssh_v6 ipv6_addr "${v6[@]}"
	fw_set open_tcp inet_service "${OPEN_TCP_PORTS[@]}"
	fw_set open_udp inet_service "${OPEN_UDP_PORTS[@]}"
	cat <<-'EOF'
	  # Filled by snippets: add rule inet archinst custom_input ...
	  chain custom_input {
	  }
	  chain custom_forward {
	  }
	  chain input {
	    type filter hook input priority filter; policy drop;
	    iif lo accept
	    ct state established,related accept
	    ct state invalid drop
	    icmp type echo-request limit rate 5/second accept
	    # Neighbour discovery and router adverts are required for IPv6 to work
	    meta l4proto ipv6-icmp accept
	    ip6 saddr fe80::/10 udp dport 546 accept
	EOF
	if ((${#v4[@]} + ${#v6[@]})); then
		echo "    tcp dport 22 ip saddr @ssh_v4 ct state new accept"
		echo "    tcp dport 22 ip6 saddr @ssh_v6 ct state new accept"
	else
		echo "    tcp dport 22 ct state new accept"
	fi
	cat <<-'EOF'
	    tcp dport @open_tcp accept
	    udp dport @open_udp accept
	    jump custom_input
	    meta l4proto tcp reject with tcp reset
	    meta l4proto udp reject
	  }
	  # Ports published by Docker are DNAT'ed and never reach input: allow them
	  # only when the published port is listed. Docker's own rules do the rest.
	  chain forward {
	    type filter hook forward priority filter; policy accept;
	    ct status dnat iifname "docker0" accept
	    ct status dnat iifname "br-*" accept
	    ct status dnat meta l4proto tcp ct original proto-dst @open_tcp accept
	    ct status dnat meta l4proto udp ct original proto-dst @open_udp accept
	    ct status dnat jump custom_forward
	    ct status dnat drop
	  }
	}
	EOF
	for f in "$FW_SNIPPETS"/*.nft; do
		[[ -r $f ]] || continue
		printf '\n# %s\n' "$f"
		cat "$f"
	done
}

# True when proto ($1) port ($2) is in OPEN_TCP_PORTS/OPEN_UDP_PORTS (ranges a-b too)
fw_port_listed() {
	local p list lo hi
	if [[ $1 == tcp ]]; then list=("${OPEN_TCP_PORTS[@]}"); else list=("${OPEN_UDP_PORTS[@]}"); fi
	for p in "${list[@]}"; do
		if [[ $p == *-* ]]; then
			lo=${p%-*} hi=${p#*-}
			(($2 >= lo && $2 <= hi)) && return 0
		elif [[ $p == "$2" ]]; then
			return 0
		fi
	done
	return 1
}

# Warns about published container ports the firewall blocks from outside: a
# reverse proxy going dark is not caught by the SSH-based rollback.
firewall_docker_check() {
	command -v docker >/dev/null && systemctl is-active -q docker || return 0
	local name ports map maps host port proto blocked=()
	while IFS=$'\t' read -r name ports; do
		IFS=',' read -ra maps <<<"$ports"
		for map in "${maps[@]}"; do
			# e.g. 0.0.0.0:8080->80/tcp or [::]:8080->80/tcp
			[[ ${map# } =~ ^(.*):([0-9]+)(-[0-9]+)?-\>[0-9-]+/(tcp|udp)$ ]] || continue
			host=${BASH_REMATCH[1]} port=${BASH_REMATCH[2]} proto=${BASH_REMATCH[4]}
			[[ $host == 127.* || $host == "[::1]" ]] && continue
			fw_port_listed "$proto" "$port" || blocked+=("$name $port/$proto")
		done
	done < <(docker ps --format '{{.Names}}\t{{.Ports}}')
	((${#blocked[@]})) || return 0
	warn "published Docker ports not in OPEN_TCP_PORTS/OPEN_UDP_PORTS, blocked from outside:"
	printf '      %s\n' "${blocked[@]}" | sort -u >&2
}

firewall_apply() {
	if [[ $FIREWALL != yes ]]; then
		firewall_disable
		return 0
	fi
	log "Configuring firewall"
	if secret iptables/iptables.rules >/dev/null || secret iptables/ip6tables.rules >/dev/null; then
		warn "secrets/iptables/*.rules are no longer used; put custom rules in $FW_SNIPPETS/*.nft"
	fi
	if ((${#SSH_ALLOW_V4[@]} + ${#SSH_ALLOW_V6[@]})); then
		warn "SSH_ALLOW_V4/SSH_ALLOW_V6 are deprecated; use one SSH_ALLOW list for both"
	fi
	pkg nftables >/dev/null
	install -d -m 755 "$FW_SNIPPETS"
	firewall_generate >"$FW_NEW"
	nft -c -f "$FW_NEW" || { rm -f "$FW_NEW"; die "generated firewall rules are invalid (see $FW_SNIPPETS)"; }
	firewall_docker_check
	install -m 644 "$ARCHINST_DIR/files/$FW_UNIT" "/etc/systemd/system/$FW_UNIT"

	if ! systemd_live; then
		# Installer chroot: nothing to protect yet, the first boot loads the rules
		mv "$FW_NEW" "$FW_FILE"
		systemctl enable -q "$FW_UNIT"
		return 0
	fi
	systemctl daemon-reload
	if fw_pending; then
		rm -f "$FW_NEW"
		die "a firewall change is still on trial; run 'archinst firewall confirm' or 'archinst firewall rollback' first"
	fi
	if cmp -s "$FW_NEW" "$FW_FILE" && nft list table inet archinst &>/dev/null && ! fw_iptables_enabled; then
		rm -f "$FW_NEW"
		systemctl enable -q "$FW_UNIT"
		log "Firewall unchanged"
		return 0
	fi

	nft -f "$FW_NEW"
	if fw_iptables_enabled; then
		# Only the INPUT chains: the rest of the iptables tables belongs to Docker
		log "Replacing the old iptables INPUT rules"
		install -d /run/archinst
		: >"$FW_MIGRATING"
		iptables -P INPUT ACCEPT
		iptables -F INPUT
		ip6tables -P INPUT ACCEPT
		ip6tables -F INPUT
	fi
	systemctl reset-failed "$FW_ROLLBACK.timer" "$FW_ROLLBACK.service" &>/dev/null || true
	systemd-run --quiet --unit="$FW_ROLLBACK" --on-active="${FIREWALL_CONFIRM_TIMEOUT}s" \
		--timer-property=AccuracySec=1s "$ARCHINST_DIR/archinst" firewall rollback

	if interactive; then
		local reply=""
		log "New firewall rules loaded; they are rolled back in ${FIREWALL_CONFIRM_TIMEOUT}s unless confirmed."
		log "Over SSH: open a NEW SSH session to this host first to check you can still get in."
		read -r -t "$((FIREWALL_CONFIRM_TIMEOUT - 5))" -p "Keep the new firewall rules? [y/N] " reply || echo
		if [[ $reply == [yY]* ]]; then
			firewall_confirm
		else
			firewall_rollback
			die "firewall rolled back; fix the configuration and re-run"
		fi
	else
		warn "new firewall rules on trial: confirm within ${FIREWALL_CONFIRM_TIMEOUT}s from a NEW SSH connection"
		warn "with 'sudo archinst firewall confirm', otherwise they are rolled back"
	fi
}

firewall_confirm() {
	# No timer: nothing on trial, or a reboot already discarded the trial rules
	if [[ ! -f $FW_NEW ]] || ! fw_pending; then
		rm -f "$FW_NEW"
		die "no firewall change on trial to confirm; run 'archinst firewall apply'"
	fi
	systemctl stop "$FW_ROLLBACK.timer" &>/dev/null || true
	mv "$FW_NEW" "$FW_FILE"
	systemctl enable -q "$FW_UNIT"
	if [[ -e $FW_MIGRATING ]]; then
		# Disable, never stop: stopping iptables.service flushes Docker's tables too
		systemctl disable -q iptables.service ip6tables.service
		local f
		for f in /etc/iptables/iptables.rules /etc/iptables/ip6tables.rules; do
			if [[ -f $f ]]; then mv "$f" "$f.archinst-old"; fi
		done
		rm -f "$FW_MIGRATING"
	fi
	log "Firewall confirmed"
}

firewall_rollback() {
	systemctl stop "$FW_ROLLBACK.timer" &>/dev/null || true
	if [[ ! -f $FW_NEW && ! -e $FW_MIGRATING ]]; then
		log "No firewall change on trial"
		return 0
	fi
	if [[ -f $FW_FILE ]]; then
		nft -f "$FW_FILE"
	else
		nft destroy table inet archinst
	fi
	if [[ -e $FW_MIGRATING ]]; then
		iptables-restore --noflush /etc/iptables/iptables.rules
		ip6tables-restore --noflush /etc/iptables/ip6tables.rules
		rm -f "$FW_MIGRATING"
	fi
	rm -f "$FW_NEW"
	warn "firewall rolled back to the previous rules"
}

firewall_disable() {
	log "Firewall disabled (FIREWALL=$FIREWALL)"
	systemctl disable -q "$FW_UNIT" &>/dev/null || true
	if systemd_live && command -v nft >/dev/null; then nft destroy table inet archinst; fi
	return 0
}

firewall_status() {
	if fw_pending; then
		warn "a firewall change is on trial:"
		systemctl list-timers "$FW_ROLLBACK.timer" --no-pager >&2
	fi
	if fw_iptables_enabled; then
		warn "the old iptables services are still enabled (run 'archinst firewall apply' to replace them)"
	fi
	nft list table inet archinst 2>/dev/null || log "Table inet archinst is not loaded"
	firewall_docker_check
}
